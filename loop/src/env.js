import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const envPath = path.join(root, ".env");

export function loadEnv() {
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!process.env[key]) process.env[key] = value;
  }
}

loadEnv();

export const ROOT = root;
export const STATE_DIR = path.join(root, "loop/state");
export const MEMORY_PATH = path.join(root, "loop/memory.json");
export const LOCAL_TICKETS = path.join(STATE_DIR, "tickets.json");
export const PENDING_PATH = path.join(STATE_DIR, "pending-merge.json");

export function ensureStateDir() {
  fs.mkdirSync(STATE_DIR, { recursive: true });
}

export function readJson(file, fallback) {
  if (!fs.existsSync(file)) return fallback;
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

export function writeJson(file, value) {
  ensureStateDir();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

export function remember(decision, why) {
  const memory = readJson(MEMORY_PATH, { decisions: [] });
  memory.decisions.push({ at: new Date().toISOString(), decision, why });
  writeJson(MEMORY_PATH, memory);
  return memory;
}

export function slug(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40);
}
